CREATE OR REPLACE FUNCTION fn_ret_numerico (
 p_gn_valor													VARCHAR(1000)
)
RETURNS VARCHAR(1000) AS $$

DECLARE
 v_return														VARCHAR(1000)			:= '';

BEGIN

--------------------------------------------------------------------------------------------------------------
--	FORMATANDO VALOR
--------------------------------------------------------------------------------------------------------------
	v_return = regexp_replace(p_gn_valor, '[^0-9]', '', 'gi');
	
--------------------------------------------------------------------------------------------------------------
--	RETORNO
--------------------------------------------------------------------------------------------------------------
	RETURN v_return;
END;
$$ LANGUAGE plpgsql;